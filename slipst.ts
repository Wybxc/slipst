/**
 * Parse the hash in the URL to get the current section, slip, and alter index.
 * The hash should be in the format "#section-slip-alter".
 */
function parseHash() {
  const hashGroups =
    /^(?<section>\d+)(?:-(?<slip>\d+))?(?:-(?<alter>\d+))?/.exec(
      location.hash.slice(1),
    )?.groups;

  let section = parseInt(hashGroups?.section ?? "1", 10);
  if (isNaN(section) || section < 1) {
    section = 1;
  }

  let slip = parseInt(hashGroups?.slip ?? "1", 10);
  if (isNaN(slip) || slip < 1) {
    slip = 1;
  }

  let alter = parseInt(hashGroups?.alter ?? "1", 10);
  if (isNaN(alter) || alter < 1) {
    alter = 1;
  }

  return { section, slip, alter };
}

const {
  section: initialSection,
  slip: initialSlip,
  alter: initialAlter,
} = parseHash();

// Presentation state. Signals re-run the layout/visibility effects below when changed.
const currentSection = signal(initialSection);
const currentSlip = signal(initialSlip);
const currentSlipAlter = signal(initialAlter);

// Persist navigation in the URL so refresh/share/back-to-position works.
effect(() => {
  const hash = `#${currentSection.value}-${currentSlip.value}-${currentSlipAlter.value}`;
  if (location.hash !== hash) {
    history.replaceState(null, "", hash);
  }
});

// Accept manual URL hash changes and synchronize them back into signals.
window.addEventListener("hashchange", () => {
  const { section, slip, alter } = parseHash();
  if (section !== currentSection.value) {
    currentSection.value = section;
  }
  if (slip !== currentSlip.value) {
    currentSlip.value = slip;
  }
  if (alter !== currentSlipAlter.value) {
    currentSlipAlter.value = alter;
  }
});

// Highest section index generated by the Typst side.
const maxSection = Array.from(document.querySelectorAll(".section"))
  .map((section) => {
    const attr = section.getAttribute("data-section");
    return attr !== null ? parseInt(attr, 10) : 0;
  })
  .reduce((a, b) => Math.max(a, b), 0);

/**
 * Map from section index to number of slips in that section.
 */
const sectionSlipCounts = new Map(
  Array.from(document.querySelectorAll(".section")).map((section) => {
    const attrSection = section.getAttribute("data-section");
    const attrCount = section.getAttribute("data-section-slip-count");
    const sectionIndex = attrSection !== null ? parseInt(attrSection, 10) : 0;
    const slipCount = attrCount !== null ? parseInt(attrCount, 10) : 1;
    return [sectionIndex, slipCount] as const;
  }),
);

/**
 * Map from a section/slip pair to number of alters.
 */
const slipAlters = new Map(
  Array.from(document.querySelectorAll(".slip")).map((slip) => {
    const attrSection = slip.getAttribute("data-section");
    const attrSlip = slip.getAttribute("data-slip");
    const attrAlter = slip.getAttribute("data-slip-alter-num");
    const sectionIndex = attrSection !== null ? parseInt(attrSection, 10) : 0;
    const slipIndex = attrSlip !== null ? parseInt(attrSlip, 10) : 0;
    const alterNum = attrAlter !== null ? parseInt(attrAlter, 10) : 1;
    return [`${sectionIndex}:${slipIndex}`, alterNum] as const;
  }),
);

function slipAlterKey(section: number, slip: number) {
  return `${section}:${slip}`;
}

/**
 * Go to the next slip or alter. Stops at the end of the current section.
 */
function nextSlip() {
  const alterNum =
    slipAlters.get(slipAlterKey(currentSection.value, currentSlip.value)) ?? 1;
  const slipCount = sectionSlipCounts.get(currentSection.value) ?? 1;
  if (currentSlipAlter.value < alterNum) {
    currentSlipAlter.value += 1;
  } else if (currentSlip.value < slipCount) {
    currentSlip.value += 1;
    currentSlipAlter.value = 1;
  }
}

/**
 * Go to the previous slip or alter. Stops at the beginning of the current section.
 */
function previousSlip() {
  if (currentSlipAlter.value > 1) {
    currentSlipAlter.value -= 1;
  } else if (currentSlip.value > 1) {
    currentSlip.value -= 1;
    const alterNum =
      slipAlters.get(slipAlterKey(currentSection.value, currentSlip.value)) ??
      1;
    currentSlipAlter.value = alterNum;
  }
}

/**
 * Go to the first slip of the next horizontal section.
 */
function nextSection() {
  if (currentSection.value < maxSection) {
    currentSection.value += 1;
    currentSlip.value = 1;
    currentSlipAlter.value = 1;
  }
}

/**
 * Go to the previous horizontal section. If toEnd is true, land on the last slip/alter.
 */
function previousSection(toEnd = false) {
  if (currentSection.value > 1) {
    currentSection.value -= 1;
    if (toEnd) {
      const lastSlip = sectionSlipCounts.get(currentSection.value) ?? 1;
      currentSlip.value = lastSlip;
      const lastAlter =
        slipAlters.get(slipAlterKey(currentSection.value, lastSlip)) ?? 1;
      currentSlipAlter.value = lastAlter;
    } else {
      currentSlip.value = 1;
      currentSlipAlter.value = 1;
    }
  }
}

const main = document.querySelector("main");

// Mouse wheels can emit many events; debounce keeps navigation to one step per gesture.
const navigateWheel = debounce(
  (event: WheelEvent) => {
    if (event.deltaY > 0) {
      // Wheel down: if at end of section, go to next section.
      if (isAtSectionEnd()) {
        nextSection();
      } else {
        nextSlip();
      }
    } else {
      // Wheel up: if at beginning of section, go to end of previous section.
      if (isAtSectionStart()) {
        previousSection(true);
      } else {
        previousSlip();
      }
    }
  },
  50,
  { edges: ["leading"] },
);

// Wheel reactivity: disable transitions during rapid scrolling, restore after a pause.
// Reads the configured duration from the CSS variable set by Typst.
const restoreTransitions = debounce(
  () => {
    document.documentElement.style.removeProperty("--transition-duration");
  },
  300,
  { edges: ["trailing"] },
);

// Check if the current position is the last slip/alter of the current section.
function isAtSectionEnd(): boolean {
  const slipCount = sectionSlipCounts.get(currentSection.value) ?? 1;
  const alterNum =
    slipAlters.get(slipAlterKey(currentSection.value, currentSlip.value)) ?? 1;
  return currentSlip.value >= slipCount && currentSlipAlter.value >= alterNum;
}

// Check if the current position is the first slip/alter of the current section.
function isAtSectionStart(): boolean {
  return currentSlip.value <= 1 && currentSlipAlter.value <= 1;
}

// Double-click/double-space detection: a fast second input at the end of a section jumps to the next section.
let clickTimer: ReturnType<typeof setTimeout> | null = null;

function handleClickOrSpace() {
  // Ensure transitions are active for click/space navigation.
  document.documentElement.style.removeProperty("--transition-duration");

  // If at end of section, wait briefly for a double input.
  if (isAtSectionEnd()) {
    if (clickTimer) {
      // Second input within 200ms → next section.
      clearTimeout(clickTimer);
      clickTimer = null;
      nextSection();
      return;
    }
    clickTimer = setTimeout(() => {
      // Single input at end of section → just nextSlip (stays in place).
      clickTimer = null;
    }, 200);
  } else {
    nextSlip();
  }
}

if (main) {
  // Left click: with transitions. Double-click at section end → next section.
  main.addEventListener("click", () => handleClickOrSpace());

  // Middle-click: short press cycles slip ↔ section, long press toggles animation mode.
  let middleDownTime = 0;
  main.addEventListener("mousedown", (event) => {
    if (event.button === 1) {
      event.preventDefault();
      middleDownTime = Date.now();
    }
  });
  main.addEventListener("auxclick", (event) => {
    if (event.button !== 1) return;
    event.preventDefault();

    // Any middle-click while in animation mode exits back to slip mode.
    if (currentMode.value === "animation") {
      currentMode.value = "slip";
      return;
    }

    const duration = Date.now() - middleDownTime;
    if (duration > 400) {
      currentMode.value = "animation";
    } else {
      currentMode.value = currentMode.value === "slip" ? "section" : "slip";
    }
  });

  // Wheel: no transitions, section wrapping. In animation mode, forwards to widgets.
  main.addEventListener(
    "wheel",
    (event) => {
      document.documentElement.style.setProperty("--transition-duration", "0s");
      restoreTransitions();

      if (currentMode.value === "animation") {
        // WIRE: feat/boxjs-animejs replaces this block
        sendWheelToBoxjsBoxes(event);
        event.preventDefault();
      } else if (currentMode.value === "section") {
        event.deltaY > 0 ? nextSection() : previousSection();
        event.preventDefault();
      } else {
        navigateWheel(event);
      }
    },
    { passive: false },
  );

  // Touch gestures.
  const anyTouch = new AnyTouch(main);
  anyTouch.on("swipeup", () => {
    document.documentElement.style.setProperty("--transition-duration", "0s");
    restoreTransitions();
    if (isAtSectionStart()) {
      previousSection(true);
    } else {
      previousSlip();
    }
  });
  anyTouch.on("swipeleft", nextSection);
  anyTouch.on("swiperight", () => previousSection());
  anyTouch.on("swipedown", () => {
    document.documentElement.style.setProperty("--transition-duration", "0s");
    restoreTransitions();
    if (isAtSectionEnd()) {
      nextSection();
    } else {
      nextSlip();
    }
  });
}

// Keyboard navigation for presenter remotes and common slideshow shortcuts.
document.addEventListener("keydown", (event) => {
  // In animation mode, arrow keys control boxjs widgets (simulate wheel).
  if (currentMode.value === "animation") {
    if (["ArrowRight", "ArrowDown"].includes(event.key)) {
      event.preventDefault();
      sendDeltaToBoxjsBoxes(100);
      return;
    } else if (["ArrowLeft", "ArrowUp"].includes(event.key)) {
      event.preventDefault();
      sendDeltaToBoxjsBoxes(-100);
      return;
    }
  }

  // Arrow Up/Down: no transitions, section wrapping (like wheel).
  if (event.key === "ArrowUp" || event.key === "PageUp") {
    event.preventDefault();
    document.documentElement.style.setProperty("--transition-duration", "0s");
    restoreTransitions();
    if (isAtSectionStart()) {
      previousSection(true);
    } else {
      previousSlip();
    }
  } else if (event.key === "ArrowDown" || event.key === "PageDown") {
    event.preventDefault();
    document.documentElement.style.setProperty("--transition-duration", "0s");
    restoreTransitions();
    if (isAtSectionEnd()) {
      nextSection();
    } else {
      nextSlip();
    }
  } else if (event.key === "ArrowRight") {
    event.preventDefault();
    nextSection();
  } else if (event.key === "ArrowLeft") {
    event.preventDefault();
    previousSection();
  }
});

// Enter key: toggles animation mode directly.
document.addEventListener("keyup", (event) => {
  if (event.key === "Enter") {
    event.preventDefault();

    // Enter always toggles animation mode (no cycle needed since arrows handle sections).
    if (currentMode.value === "animation") {
      currentMode.value = "slip";
    } else {
      currentMode.value = "animation";
    }
  }
});

// Space: with transitions. Double-space at section end → next section.
document.addEventListener("keydown", (event) => {
  if (event.key === " " && !event.ctrlKey && !event.metaKey) {
    event.preventDefault();
    handleClickOrSpace();
  }
});

