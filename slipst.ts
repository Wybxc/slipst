// Toggle visibility of every generated slip layer.
// Previous slips keep only their final alter visible; current slip shows its active alter;
// future slips stay hidden until navigation reaches them.
effect(() => {
  document.querySelectorAll(".slip").forEach((slip) => {
    const attrSlip = slip.getAttribute("data-slip");
    const slipIndex = attrSlip !== null ? parseInt(attrSlip, 10) : 0;

    const attrSection = slip.getAttribute("data-section");
    const sectionIndex = attrSection !== null ? parseInt(attrSection, 10) : 0;

    const attrAlter = slip.getAttribute("data-slip-alter-idx");
    const alterIdx = attrAlter !== null ? parseInt(attrAlter, 10) : 1;

    if (slip instanceof HTMLElement) {
      if (sectionIndex !== currentSection.value) {
        // Inactive sections are prepared at their first slip so horizontal
        // navigation arrives at the beginning instead of moving diagonally.
        if (slipIndex === 1 && alterIdx === 1) {
          slip.style.opacity = "1";
        } else {
          slip.style.opacity = "0";
        }
      } else if (slipIndex < currentSlip.value) {
        // Previous slips, only show the last alter.
        if (
          alterIdx !==
          (slipAlters.get(slipAlterKey(sectionIndex, slipIndex)) ?? 1)
        ) {
          slip.style.opacity = "0";
        } else {
          slip.style.opacity = "1";
        }
      } else if (slipIndex === currentSlip.value) {
        // Current slip, show the current alter.
        if (alterIdx === currentSlipAlter.value) {
          slip.style.opacity = "1";
        } else {
          slip.style.opacity = "0";
        }
      } else {
        // Future slips, hide all alters.
        slip.style.opacity = "0";
      }
    }
  });
});

// Move the vertical container according to the latest active #up action.
// Without #up, the deck stays aligned to the top; with #up, the target slip is brought up.
const layoutEffect = () => {
  const sectionContainer = document.getElementById("section-container");
  const section = document.querySelector(
    `.section[data-section="${currentSection.value}"]`,
  );
  if (
    sectionContainer instanceof HTMLElement &&
    section instanceof HTMLElement
  ) {
    sectionContainer.style.left = `${-section.offsetLeft}px`;
  }

  document.querySelectorAll(".slip-container").forEach((container) => {
    if (container instanceof HTMLElement) {
      container.style.top = "0";
    }
  });

  // Find the nearest slip with a "data-slip-up" attribute, starting from the current slip and going upwards.
  let up = document
    .querySelector(
      `.slip[data-section="${currentSection.value}"][data-slip="${currentSlip.value}"]`,
    )
    ?.getAttribute("data-slip-up");
  let dy = document
    .querySelector(
      `.slip[data-section="${currentSection.value}"][data-slip="${currentSlip.value}"]`,
    )
    ?.getAttribute("data-slip-dy");
  let end = document
    .querySelector(
      `.slip[data-section="${currentSection.value}"][data-slip="${currentSlip.value}"]`,
    )
    ?.getAttribute("data-slip-end");

  for (let i = currentSlip.value - 1; i > 0; i--) {
    if (isNotNil(up)) break;
    up = document
      .querySelector(
        `.slip[data-section="${currentSection.value}"][data-slip="${i}"]`,
      )
      ?.getAttribute("data-slip-up");
    dy = document
      .querySelector(
        `.slip[data-section="${currentSection.value}"][data-slip="${i}"]`,
      )
      ?.getAttribute("data-slip-dy");
    end = document
      .querySelector(
        `.slip[data-section="${currentSection.value}"][data-slip="${i}"]`,
      )
      ?.getAttribute("data-slip-end");
  }
  const endDyRaw = getComputedStyle(
    document.getElementById("section-container")!,
  )
    .getPropertyValue("--end-dy")
    .trim()
    .replace(/\u2212/g, "-");
  const endDyValue = endDyRaw ? parseFloat(endDyRaw) : 0;
  const startDyRaw = getComputedStyle(
    document.getElementById("section-container")!,
  )
    .getPropertyValue("--start-dy")
    .trim()
    .replace(/\u2212/g, "-");
  const startDyValue = startDyRaw ? parseFloat(startDyRaw) : 0;
  let dyValue = isNotNil(dy) ? parseFloat(dy.replace(/\u2212/g, "-")) : 0;
  if (isNotNil(up)) {
    const anchors = document.querySelectorAll(`[data-global-slip="${up}"]`);
    const anchor = Array.from(anchors)
      .filter((anchor) => anchor instanceof HTMLElement)
      .filter(
        (anchor) => window.getComputedStyle(anchor).display !== "none",
      )[0];
    const container = document.querySelector(
      `.slip-container[data-section="${currentSection.value}"]`,
    );
    if (!(anchor instanceof HTMLElement)) {
      console.warn(`Slipst #up target does not exist: global slip ${up}`);
    }
    if (anchor instanceof HTMLElement && container instanceof HTMLElement) {
      const marginTop =
        parseFloat(window.getComputedStyle(container).marginTop) || 0;
      if (end === "true") {
        // Align the target slip bottom with the viewport bottom.
        const viewportHeight =
          container.closest("main")?.clientHeight ?? window.innerHeight;
        const anchorBottom =
          marginTop + anchor.offsetTop + anchor.getBoundingClientRect().height;
        const totalDy = dyValue + endDyValue;
        const sign = totalDy >= 0 ? "+" : "-";
        container.style.top = `calc(${viewportHeight - anchorBottom}px ${sign} ${Math.abs(totalDy)} * var(--slip-1cm))`;
      } else {
        const totalDy = dyValue + startDyValue;
        if (totalDy !== 0) {
          const sign = totalDy >= 0 ? "-" : "+";
          container.style.top = `calc(${-anchor.offsetTop - marginTop}px ${sign} ${Math.abs(totalDy)} * var(--slip-1cm))`;
        } else {
          container.style.top = `${-anchor.offsetTop - marginTop}px`;
        }
      }
    }
  }
};
effect(layoutEffect);

// During resize, recompute layout instantly to avoid seeing an animated correction jump.
if (document.defaultView) {
  document.defaultView.addEventListener("resize", () => {
    document.documentElement.style.setProperty("--transition-duration", "0s");
    document.documentElement.style.setProperty(
      "--section-transition-duration",
      "0s",
    );
    layoutEffect();
    setTimeout(() => {
      document.documentElement.style.removeProperty("--transition-duration");
      document.documentElement.style.removeProperty(
        "--section-transition-duration",
      );
    }, 1);
  });
}
